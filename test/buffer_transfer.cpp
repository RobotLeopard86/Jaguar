#include <iterator>
#include <libjaguar/Document.hpp>
#include <sstream>
#include <vector>

int main() {
	try {
		std::vector<unsigned char> buf = {0x0B, 0x05, 'b', 'y', 't', 'e', 's', 0x4A, 0x00, 0x00,
			0x00, 0xEE, 0xFF, 0x21, 0x72, 0x9A, 0xA3, 0xB2, 0x21, 0x00, 0x00, 0xFF, 0xE3,
			0xE7, 0x67, 0x41, 0x69, 0x37, 0xAA, 0xBB, 0x99, 0xCC, 0x74, 0x8E, 0xCE, 0xD6,
			0xE5, 0xF1, 0x04, 0x00, 0x51, 0x2E, 0xAA, 0x71, 0x82, 0x73, 0x74, 0x75, 0x9B,
			0xAC, 0xBC, 0xFF, 0xEE, 0xDD, 0xCC, 0xBB, 0xAA, 0x99, 0x88, 0x77, 0x66, 0x55,
			0x44, 0x33, 0x22, 0x11, 0x00, 0x00, 0xA3, 0xA7, 0xC1, 0xCF, 0xE8, 0xA1, 0x48,
			0x84, 0x9E, 0x8F, 0x12, 0x2B, 0xEA, 0x96, 0x42, 0xFF, 0x17};
		std::string str(reinterpret_cast<char*>(buf.data()), buf.size());
		std::unique_ptr<std::istringstream> iss = std::make_unique<std::istringstream>(str);
		libjaguar::Document doc(std::move(iss));
		std::stringstream ss;
		doc.ExportTo(ss);
		std::vector<unsigned char> reencoded;
		std::ranges::copy(std::istreambuf_iterator<char>(ss), std::istreambuf_iterator<char>(), std::back_inserter(reencoded));
		for(unsigned int i = 0; i < reencoded.size(); ++i) {
			if(buf[i] != reencoded[i]) return -1;
		}
		{
			reencoded = doc.QueryValue<std::vector<unsigned char>>("bytes");
		}
		return 0;
	} catch(...) {
		return -1;
	}
}
